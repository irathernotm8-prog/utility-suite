// Mixer — regenerates src/core/levels.js: renders one note of every instrument and one hit of every drum voice in
// every kit, measures the peak and stores the gain that lands it on its target. Run: xvfb-run -a electron test/calibrate.js
'use strict';
const path = require('path'); const fs = require('fs');
const { app, BrowserWindow } = require('electron');
app.whenReady().then(async () => {
  const w = new BrowserWindow({ show: false, webPreferences: { backgroundThrottling: false } });
  await w.loadFile(path.join(__dirname, '..', 'src', 'engine', 'engine.html'));
  const r = await w.webContents.executeJavaScript(`(async () => {
    MXLevels.inst = {}; MXLevels.kit = {};
    const peak = (b) => { let p = 0; for (let c = 0; c < b.numberOfChannels; c++) for (const v of b.getChannelData(c)) p = Math.max(p, Math.abs(v)); return p; };
    const out = { inst: {}, kit: {} }; const sr = 32000;
    for (const P of MXSounds.INSTRUMENTS) {
      const pk = []; for (const m of (P.cat === 'Bass' ? [36, 43] : [60, 67])) { const ctx = new OfflineAudioContext(2, sr * 4, sr); MXLevels.inst[P.id] = 1; MXSynth.playNote(ctx, ctx.destination, P, m, 0.02, P.cat === 'Pads' || P.cat === 'FX' ? 2.5 : 0.8, 0.8, { bpm: 120 }); pk.push(peak(await ctx.startRendering())); }
      const p = Math.max(...pk); out.inst[P.id] = +(Math.pow(10, -12 / 20) / Math.max(1e-4, p)).toFixed(4);
    }
    const TARGET = { kick: -6, snare: -7, clap: -7, rim: -12, hat: -11, openhat: -11, tom_low: -9, tom_mid: -9, tom_high: -10, crash: -10, ride: -12, shaker: -15, cowbell: -13, perc: -11, snap: -10, riser: -11, downlifter: -11, impact: -7 };
    for (const k of MXSounds.KITS) { out.kit[k.id] = {}; for (const v of Object.keys(TARGET)) { const ctx = new OfflineAudioContext(2, sr * 6, sr); MXLevels.kit[k.id] = { [v]: 1 }; MXDrums.hit(ctx, ctx.destination, k.id, v, 0.02, 1, { bpm: 120 }); const p = peak(await ctx.startRendering()); out.kit[k.id][v] = +(Math.pow(10, TARGET[v] / 20) / Math.max(1e-4, p)).toFixed(4); } }
    return out; })()`);
  const f = path.join(__dirname, '..', 'src', 'core', 'levels.js');
  fs.writeFileSync(f, `// Mixer — level calibration (generated by test/calibrate.js; run it again after changing a preset). Each instrument's
// gain makes a velocity-0.8 note peak near −12 dBFS; each drum voice peaks at a level typical of a balanced kit.
(function (root, factory) { if (typeof module === 'object' && module.exports) module.exports = factory(); else root.MXLevels = factory(); })(typeof self !== 'undefined' ? self : this, function () {
  return ${JSON.stringify(r)};
});
`);
  console.log('wrote', f, Object.keys(r.inst).length, 'instruments'); app.exit(0);
});
